"""Trains the classifier and anomaly detectors on synthetic claims and deploys the result.

    python -m scripts.train_xgboost [--version v1.0.0] [--no-deploy]

Run on the training machine. To serve the model to another machine, start scripts/ml_server.py
here and set ML_SERVER_URL on the application server."""
import argparse
import asyncio
import json
from pathlib import Path

from app.config import get_settings
from app.db.seed.synthetic import generate, training_matrix_with_groups
from app.detection.ml.training import set_current, train_models


async def register(meta: dict, path: Path, deployed: bool) -> None:
    from app.db.session import create_all, dispose_engine, session_scope
    from app.services import model_service

    if get_settings().database_url.startswith("sqlite"):
        await create_all()
    async with session_scope() as db:
        await model_service.register(db, meta, str(path), deployed=deployed, notes="Trained on synthetic claims with planted patterns.")
    await dispose_engine()


def render_model_card(meta: dict) -> str:
    """docs/model_card.md, generated from the training run so its numbers cannot drift."""
    from app.services.model_service import INTENDED_USE, LIMITATIONS, OUT_OF_SCOPE

    ev = meta["evaluation"]
    r, p = ev["random_split"], ev["provider_split"]

    def cell(d, key):
        return "not yet measured" if not d or d.get(key) is None else f"{d[key]:.4f}"

    rows = "\n".join(f"| {label} | {cell(r, key)} | {cell(p, key)} |" for label, key in (("F1", "f1"), ("Precision", "precision"), ("Recall", "recall"), ("ROC AUC", "roc_auc"), ("PR AUC", "pr_auc"), ("False positive rate", "false_positive_rate"), ("False negative rate", "false_negative_rate")))
    features = "\n".join(f"| `{k}` | {v:.1%} |" for k, v in list(meta["feature_importance"].items())[:10])
    return f"""# Model card: ClaimShield FWA classifier {meta['version']}

> **{meta['warning']}** Generated by `scripts/train_xgboost.py` on {meta['trained_at'][:10]}. Do not edit by hand.

## Model name and version

- **Name:** ClaimShield FWA classifier (`{meta['model_type']}`), with isolation forest and local outlier factor anomaly scores
- **Version:** {meta['version']}
- **Features:** {len(meta['features'])} (see `app/detection/ml/feature_engineering.py`)
- **Explanations:** per-claim TreeSHAP attributions

## Training data

{meta['training_samples']:,} synthetic claims, of which {meta['positive_rate']:.1%} carry a planted billing pattern (duplicate billing, upcoding, unbundling, excessive utilisation, impossible day, referral ring, services with no encounter, identity misuse). No real claims and no protected health information. Labels come from the planting script, plus any reviewer decisions recorded in the system at retraining time.

## Metrics

| Metric | Random split (25% of claims held out) | Provider split (providers never seen in training) |
|---|---|---|
{rows}

- Random split: {r['test_claims']:,} test claims, {r['test_positives']:,} positive.
- Provider split: {('%s, %d providers, %d of them with planted patterns' % (p['method'], p['providers'], p['providers_with_planted_patterns'])) if p else 'not run'}.
- {ev['note']}

## Anomaly calibration

Log-logistic anomaly indices are calibrated on held-out normal claims, separate from fitting and validation. Median maps to 0.30, calibration p97 to the signal threshold 0.80, and the smooth upper limit is 0.99. Anomaly-only severity is capped at medium; scores are not fraud probabilities.

```json
{json.dumps(meta.get("anomaly_evaluation", {}), indent=2)}
```

## IMPORTANT LIMITATIONS

{chr(10).join('- ' + l for l in LIMITATIONS)}
- The random-split figures are inflated: claims from the same provider appear in both training and test data, so the model can recognise the provider. Use the provider-split column.
- With only {p['providers_with_planted_patterns'] if p else 'a few'} providers carrying planted patterns, the provider-split figures are themselves unstable and would change with a different synthetic seed.

## Intended use

{INTENDED_USE}

Not intended for:

{chr(10).join('- ' + o for o in OUT_OF_SCOPE)}

## Bias analysis (which features dominate)

{chr(10).join('- ' + b for b in meta['bias_analysis'])}

| Feature | Share of total gain |
|---|---|
{features}

## Fairness considerations

Not yet measured. No analysis has been run of score or false-positive differences across provider groups (rural or urban, solo or group practice, specialty) or member groups (age, low-income area). This must be done on real, reviewed cases before any production use.
"""


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--version", default="v1.0.0")
    parser.add_argument("--seed", type=int, default=7)
    parser.add_argument("--no-deploy", action="store_true")
    parser.add_argument("--no-register", action="store_true", help="Skip writing the model card to the database")
    args = parser.parse_args()

    out = Path(get_settings().artifacts_dir)
    data = generate(seed=args.seed)
    X, y, groups = training_matrix_with_groups(data)
    print(f"Training on {len(y)} synthetic claims ({int(y.sum())} with planted patterns, {y.mean():.1%}).")
    meta = train_models(X, y, args.version, out, seed=args.seed, groups=groups)
    if not args.no_deploy:
        set_current(out, args.version)
    print("Random split:  ", json.dumps(meta["evaluation"]["random_split"]))
    print("Provider split:", json.dumps(meta["evaluation"]["provider_split"]))
    Path("docs").mkdir(exist_ok=True)
    Path("docs/model_card.md").write_text(render_model_card(meta), encoding="utf-8")
    print("Model card written to docs/model_card.md")
    print("Anomaly validation:", json.dumps(meta["anomaly_evaluation"]))
    print("Top features:", ", ".join(list(meta["feature_importance"])[:5]))
    if not args.no_register:
        asyncio.run(register(meta, out / args.version, deployed=not args.no_deploy))
    print(f"Artifacts written to {out / args.version}" + ("" if args.no_deploy else " and set as CURRENT."))


if __name__ == "__main__":
    main()
