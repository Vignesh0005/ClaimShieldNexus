"""Measures ingest-plus-detection latency and throughput and writes a report.

    python -m scripts.benchmark_throughput [--claims 500] [--out docs/benchmark_latest.md]

By default it runs against a throwaway SQLite file so the demo database is not touched. To measure
another database, pass --database-url (for example a PostgreSQL URL); the script creates a tenant
named benchmark-<timestamp> there and leaves it in place.

What is measured: one claim at a time, in one process: validate, store, run the full detection
pipeline, commit. That is the path a single in-process worker takes. It says nothing about
several workers in parallel, which this script does not attempt."""
import argparse
import asyncio
import os
import platform
import sys
import tempfile
import time
from datetime import date, datetime, timezone
from pathlib import Path


def parse() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--claims", type=int, default=500)
    parser.add_argument("--database-url", default=None)
    parser.add_argument("--out", default="docs/benchmark_latest.md")
    return parser.parse_args()


async def run(args: argparse.Namespace, database_url: str) -> str:
    from app.config import get_settings
    from app.core import perf
    from app.core.logging import configure_logging
    from app.db.seed.seed_coverage_rules import seed_coverage_rules
    from app.db.seed.seed_demo_tenant import seed_tenant
    from app.db.seed.seed_synthetic import seed_reference_data
    from app.db.seed.synthetic import generate, public_claim
    from app.db.session import create_all, dispose_engine, session_scope
    from app.detection.ml.registry import registry
    from app.services import claim_service

    settings = get_settings()
    settings.log_level = "ERROR"
    configure_logging()
    if database_url.startswith("sqlite"):
        await create_all()
    async with session_scope() as db:
        await seed_coverage_rules(db)
        tenant, _ = await seed_tenant(db, "Benchmark", f"benchmark-{int(time.time())}")
    model_loaded = registry.load()

    data = generate(seed=21, n_providers=40, n_members=400, days=90, end=date.today(), daily_rate=0.25)
    step = max(1, len(data.claims) // args.claims)
    claims = data.claims[::step][: args.claims]
    planted = sum(c["_label"] for c in claims)

    latencies: list[float] = []
    flagged = routed = 0
    perf.reset()
    async with session_scope(tenant.id) as db:
        await seed_reference_data(db, tenant, data)
        await db.commit()
        started = time.perf_counter()
        for raw in claims:
            t0 = time.perf_counter()
            _, _, result = await claim_service.ingest_record(db, tenant, public_claim(raw), source="benchmark", process=True)
            await db.commit()
            latencies.append((time.perf_counter() - t0) * 1000)
            flagged += bool(result and result.signals)
            routed += bool(result and result.case_id)
        elapsed = time.perf_counter() - started
    await dispose_engine()

    end_to_end = perf.percentiles(latencies)
    pipeline_only = perf.summary()["latency_ms"]
    per_second = len(claims) / elapsed
    dialect = database_url.split("+")[0].split(":")[0]
    return f"""# Throughput benchmark

Generated by `scripts/benchmark_throughput.py` on {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}. These are measurements from one run on one machine, not targets.

## Setup

| | |
|---|---|
| Database | {dialect} ({'throwaway file' if args.database_url is None else 'supplied URL'}) |
| Processing | one claim at a time, one process, detection in-process |
| ML model | {('local artifacts ' + str(registry.version)) if model_loaded else 'none loaded (rules, graph and temporal detectors only)'} |
| Claims | {len(claims):,} synthetic claims in date order, {planted:,} with planted patterns |
| Machine | {platform.system()} {platform.release()}, {platform.machine()}, {os.cpu_count()} logical CPUs, Python {sys.version.split()[0]} |

## Results

| Measure | Value |
|---|---|
| Total time | {elapsed:.1f} s |
| Throughput | {per_second:.2f} claims/second ({per_second * 60:.0f} claims/minute) |
| Latency per claim, end to end (validate, store, detect, commit) | p50 {end_to_end['p50']:.0f} ms, p95 {end_to_end['p95']:.0f} ms, p99 {end_to_end['p99']:.0f} ms, mean {end_to_end['mean']:.0f} ms |
| Latency per claim, detection pipeline only | p50 {pipeline_only['p50']:.0f} ms, p95 {pipeline_only['p95']:.0f} ms, p99 {pipeline_only['p99']:.0f} ms, mean {pipeline_only['mean']:.0f} ms |
| Claims with at least one finding | {flagged:,} of {len(claims):,} |
| Claims routed to a case | {routed:,} of {len(claims):,} |

## How to read this

- Latency grows through the run because each claim is compared with its provider's and member's earlier claims, and busy flagged providers accumulate history. The p95 and p99 figures are mostly those providers.
- This is a single worker. {per_second * 60:.0f} claims/minute is **{'below' if per_second * 60 < 1000 else 'at or above'}** 1,000 claims/minute.
- Parallel workers, PostgreSQL and Redis have not been measured. See `docs/scaling.md` for what would need to change and what is still unknown.
"""


def main() -> None:
    args = parse()
    tmp = None
    if args.database_url:
        url = args.database_url
    else:
        tmp = Path(tempfile.mkdtemp(prefix="claimshield-bench-")) / "bench.db"
        url = f"sqlite+aiosqlite:///{tmp.as_posix()}"
    # Must be set before any app module reads its settings.
    os.environ["DATABASE_URL"] = url
    os.environ.setdefault("REDIS_URL", "")
    report = asyncio.run(run(args, url))
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text(report, encoding="utf-8")
    print(report)
    print(f"Report written to {args.out}")
    if tmp is not None:
        tmp.unlink(missing_ok=True)


if __name__ == "__main__":
    main()
